-- FUNCTION: set_updated_at()
-- PURPOSE: Automatically refreshes the updated_at timestamp to now() before any UPDATE.
-- SECURITY: 'security invoker' runs with privileges of the user executing the update.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Attach set_updated_at triggers to all mutable tables:
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create trigger auction_lots_set_updated_at
before update on public.auction_lots
for each row execute function public.set_updated_at();

create trigger journal_articles_set_updated_at
before update on public.journal_articles
for each row execute function public.set_updated_at();

create trigger contact_messages_set_updated_at
before update on public.contact_messages
for each row execute function public.set_updated_at();

create trigger site_settings_set_updated_at
before update on public.site_settings
for each row execute function public.set_updated_at();

-- FUNCTION: handle_new_user()
-- PURPOSE: Automatically provisions a public profile row whenever a new user
-- registers via Supabase auth (Google OAuth or Email/Password).
-- SECURITY DEFINER: Runs with elevated privileges of the function owner, allowing
-- it to write to public.profiles during user registration.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, nullif(new.raw_user_meta_data ->> 'name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

-- Restrict execution so external clients cannot invoke this function manually.
revoke all on function public.handle_new_user() from public;

-- TRIGGER: on_auth_user_created
-- Fires immediately after an INSERT on auth.users.
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- FUNCTION: is_super_admin()
-- PURPOSE: Validates whether the currently authenticated session belongs to a super_admin.
-- HOW IT WORKS: Checks if auth.uid() exists in user_roles with role = 'super_admin'.
-- WHY CALLED BY CLIENT: Used by admin.js to verify entry into the admin room.
create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.user_roles
    where user_id = (select auth.uid())
      and role = 'super_admin'
  );
$$;

-- Allow anon and authenticated roles to execute this verification function.
revoke all on function public.is_super_admin() from public;
grant execute on function public.is_super_admin() to anon, authenticated;

-- FUNCTION: update_bid_summary()
-- PURPOSE: Atomic bid counter and price updater.
-- HOW IT WORKS: When a new bid is inserted into public.bids, this trigger automatically
-- updates the parent auction lot's current_bid (taking the greatest amount) and
-- increments bid_count by 1 in a single atomic database transaction.
create or replace function public.update_bid_summary()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.auction_lots
  set current_bid = greatest(current_bid, new.amount),
      bid_count = bid_count + 1,
      updated_at = now()
  where id = new.lot_id;
  return new;
end;
$$;

revoke all on function public.update_bid_summary() from public;

create trigger bids_update_lot_summary
after insert on public.bids
for each row execute function public.update_bid_summary();

-- =============================================================================
-- 5. Row Level Security (RLS) Policies
-- =============================================================================
-- WHAT IS RLS:
-- By default, PostgreSQL allows any authorized role to read all rows in a table.
-- Enabling RLS means EVERY query is automatically intercepted and filtered by
-- SQL policy rules. If a row does not satisfy the 'using' clause, PostgreSQL
-- acts as if the row does not exist, protecting data at the database level!

alter table public.profiles enable row level security;
alter table public.user_roles enable row level security;
alter table public.auction_lots enable row level security;
alter table public.lot_images enable row level security;
alter table public.bids enable row level security;
alter table public.saved_lots enable row level security;
alter table public.journal_articles enable row level security;
alter table public.contact_messages enable row level security;
alter table public.admin_audit_logs enable row level security;
alter table public.site_settings enable row level security;

-- POLICY: Profiles
-- Users can only read their own profile; super_admin can inspect any profile.
create policy "Profiles are visible to their owner or super admin"
on public.profiles for select
to authenticated
using ((select auth.uid()) = id or public.is_super_admin());

-- Users can only update their own profile fields.
create policy "Users may update their own profile"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

-- POLICY: user_roles
-- Only the super_admin can read role assignments (prevents role discovery by users).
create policy "Super admin can view roles"
on public.user_roles for select
to authenticated
using (public.is_super_admin());

-- POLICY: auction_lots
-- Anonymous visitors and authenticated users can only view lots that are published
-- and in scheduled, live, or closed states. Draft or withdrawn lots are hidden
-- from the public, but visible to the super_admin.
create policy "Published lots are public"
on public.auction_lots for select
to anon, authenticated
using (
  (
    published_at is not null
    and status in ('scheduled', 'live', 'closed')
  )
  or public.is_super_admin()
);

-- POLICY: lot_images
-- Images can be viewed publicly only if their parent auction lot is published.
create policy "Images belong to public lots"
on public.lot_images for select
to anon, authenticated
using (
  exists (
    select 1
    from public.auction_lots
    where auction_lots.id = lot_images.lot_id
      and (
        (
          auction_lots.published_at is not null
          and auction_lots.status in ('scheduled', 'live', 'closed')
        )
        or public.is_super_admin()
      )
  )
);

-- POLICY: bids
-- Authenticated users can only see their own bid history; super_admin sees all.
create policy "Users may view their own bids"
on public.bids for select
to authenticated
using ((select auth.uid()) = bidder_id or public.is_super_admin());

-- POLICY: saved_lots
-- Users can only manage (insert, select, delete) items in their own watchlist.
create policy "Users may manage their own saved lots"
on public.saved_lots for all
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

-- POLICY: journal_articles
-- Published articles are readable by everyone; drafts are restricted to super_admin.
create policy "Published journal articles are public"
on public.journal_articles for select
to anon, authenticated
using (is_published or public.is_super_admin());

-- POLICY: contact_messages & audit_logs
-- Only super_admin can review customer messages and audit logs.
create policy "Super admin can view contact messages"
on public.contact_messages for select
to authenticated
using (public.is_super_admin());

create policy "Super admin can view audit logs"
on public.admin_audit_logs for select
to authenticated
using (public.is_super_admin());

-- POLICY: site_settings
-- Public settings (e.g. site notice banner) are readable by all; private are admin-only.
create policy "Public site settings are readable"
on public.site_settings for select
to anon, authenticated
using (is_public or public.is_super_admin());

-- ADMINISTRATIVE MANAGEMENT POLICIES (Full CRUD for Super Admin):
create policy "Super admin manages auction lots"
on public.auction_lots for all
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

create policy "Super admin manages lot images"
on public.lot_images for all
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

create policy "Super admin manages journal articles"
on public.journal_articles for all
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

create policy "Super admin manages contact messages"
on public.contact_messages for update
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

create policy "Super admin may remove contact messages"
on public.contact_messages for delete
to authenticated
using (public.is_super_admin());

create policy "Super admin manages site settings"
on public.site_settings for all
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

