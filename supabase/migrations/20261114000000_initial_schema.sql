-- =============================================================================
-- THE VAULT — Backend Database Schema & Security Migration
-- =============================================================================
-- WHAT THIS FILE IS:
-- This is a PostgreSQL database migration file executed in Supabase.
-- It establishes the complete data foundation for THE VAULT digital auction house,
-- defining tables, relationships, constraints, automated triggers, stored functions,
-- and Row Level Security (RLS) policies.
--
-- VIVA EXPLANATION KEY POINTS:
-- 1. PostgreSQL: An advanced, open-source relational database management system (RDBMS).
-- 2. Supabase: An open-source Firebase alternative built on PostgreSQL. It handles
--    user authentication and gives us an instant RESTful API through PostgREST.
-- 3. Row Level Security (RLS): A database-level security barrier that filters rows
--    based on the logged-in user's identity (auth.uid()), preventing unauthorized access
--    even if someone calls the API directly from the browser console.
-- =============================================================================

-- Enable the 'pgcrypto' extension.
-- WHY: Provides cryptographic functions, specifically gen_random_uuid(),
-- which allows the database to automatically generate secure, unpredictable
-- 128-bit UUID primary keys for new rows without needing client-side generation.
create extension if not exists pgcrypto;

-- =============================================================================
-- 1. Custom Enumeration Types (ENUMs)
-- =============================================================================
-- WHY USE ENUMS:
-- An ENUM (enumerated type) restricts a column to a strict, predefined set of
-- valid text values. This prevents invalid strings (like 'pending' or 'LIVE')
-- from ever being inserted into the database.

-- Defines the life-cycle states of an auction item.
-- 'draft': Created by admin, not yet visible to the public.
-- 'scheduled': Published and visible, but bidding hasn't opened yet.
-- 'live': Currently active; bids can be submitted.
-- 'closed': Auction time has expired; winner determined.
-- 'withdrawn': Removed from auction by administrative decision.
create type public.auction_lot_status as enum (
  'draft',
  'scheduled',
  'live',
  'closed',
  'withdrawn'
);

-- Defines administrative roles. Only designated super_admins have full access.
create type public.user_role as enum ('super_admin');

-- Tracks the resolution workflow of customer support inquiries.
create type public.contact_message_status as enum (
  'new',
  'in_progress',
  'resolved',
  'spam'
);

-- =============================================================================
-- 2. Core Relational Tables
-- =============================================================================

-- TABLE: profiles
-- WHAT: Stores public profile information for registered users.
-- RELATIONSHIP: 1-to-1 with Supabase's internal auth.users table.
-- WHY: Keeps application-specific user data in the 'public' schema while
-- keeping sensitive authentication credentials securely locked inside 'auth.users'.
create table public.profiles (
  -- Primary key linked directly to auth.users.
  -- 'on delete cascade' means if the auth account is deleted, this profile is deleted too.
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- TABLE: user_roles
-- WHAT: Role-Based Access Control (RBAC) mapping table.
-- WHY: Decouples role assignment from profile data. Ensures that admin privileges
-- are explicitly recorded and can only be queried through secure RPC functions.
create table public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role public.user_role not null,
  created_at timestamptz not null default now()
);

-- Enforce single super-admin constraint:
-- Guarantees that at most one super_admin user can exist in the system at any time.
create unique index user_roles_one_super_admin_idx
  on public.user_roles (role);

-- TABLE: auction_lots
-- WHAT: The central entity of THE VAULT — stores all auction items.
-- CONTAINS: Provenance, estimate prices, live bid totals, countdown schedules, and status.
create table public.auction_lots (
  -- Primary key: Unique 128-bit identifier generated by pgcrypto.
  id uuid primary key default gen_random_uuid(),
  
  -- Friendly short identifier (e.g. 'watch', 'camera') used in demo data & URL slugs.
  legacy_id text not null unique,
  
  -- Curatorial catalog number (e.g. '024', '031').
  lot_number text not null unique,
  
  -- Category classification (e.g. 'Timepieces', 'Fine Art', 'Automotive').
  category text not null,
  period text,
  title text not null,
  subtitle text,
  description text,
  
  -- Financial estimates: numeric(14, 2) ensures exact decimal precision without
  -- floating-point rounding errors (stores up to 12 integer digits and 2 decimal places).
  estimate_low numeric(14, 2),
  estimate_high numeric(14, 2),
  current_bid numeric(14, 2) not null default 0,
  bid_count integer not null default 0 check (bid_count >= 0),
  
  -- Auction schedule timestamps (timestamptz stores UTC with timezone awareness).
  starts_at timestamptz,
  ends_at timestamptz,
  status public.auction_lot_status not null default 'draft',
  published_at timestamptz,
  
  -- Foreign key tracking which administrator created this lot.
  -- 'on delete set null' preserves the auction record even if the admin account is removed.
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- CHECK CONSTRAINTS:
  -- 1. Ensure estimate_high is never less than estimate_low.
  constraint auction_lots_estimate_range_check
    check (
      estimate_low is null
      or estimate_high is null
      or estimate_high >= estimate_low
    ),
  -- 2. Ensure current bid can never be negative.
  constraint auction_lots_current_bid_check check (current_bid >= 0),
  -- 3. Ensure auction end time is chronologically after start time.
  constraint auction_lots_schedule_check
    check (starts_at is null or ends_at is null or ends_at > starts_at)
);

-- TABLE: lot_images
-- WHAT: Stores high-resolution photography associated with an auction lot.
-- RELATIONSHIP: Many-to-1 with auction_lots (one lot can have multiple gallery angles).
create table public.lot_images (
  id uuid primary key default gen_random_uuid(),
  lot_id uuid not null references public.auction_lots(id) on delete cascade,
  image_url text not null,
  alt_text text not null,
  sort_order integer not null default 0 check (sort_order >= 0),
  is_primary boolean not null default false,
  created_at timestamptz not null default now()
);

-- PARTIAL UNIQUE INDEX:
-- Guarantees that each lot has at most ONE primary thumbnail image (where is_primary = true).
-- Other angles for the same lot have is_primary = false.
create unique index lot_images_one_primary_idx
  on public.lot_images (lot_id)
  where is_primary;

-- TABLE: bids
-- WHAT: Immutable audit ledger recording every bid submitted across the platform.
-- RELATIONSHIP: Connects a bidder (auth.users) to an auction lot (auction_lots).
-- WHY 'on delete restrict': Neither an active lot nor an active user can be deleted
-- while historical financial bid records reference them, ensuring audit trail integrity.
create table public.bids (
  id uuid primary key default gen_random_uuid(),
  lot_id uuid not null references public.auction_lots(id) on delete restrict,
  bidder_id uuid not null references auth.users(id) on delete restrict,
  amount numeric(14, 2) not null check (amount > 0),
  created_at timestamptz not null default now()
);

-- TABLE: saved_lots
-- WHAT: User watchlist join table (many-to-many relationship between users and lots).
-- PRIMARY KEY (user_id, lot_id): Composite primary key prevents a user from saving
-- the same lot more than once.
create table public.saved_lots (
  user_id uuid not null references auth.users(id) on delete cascade,
  lot_id uuid not null references public.auction_lots(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, lot_id)
);

-- TABLE: journal_articles
-- WHAT: Editorial publication stories and curatorial essays.
-- JSONB body: Allows rich editorial blocks (paragraphs, pull-quotes, subheadings)
-- to be stored as a structured JSON array without complex multi-table joins.
create table public.journal_articles (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  category text not null,
  title text not null,
  subtitle text not null,
  image_url text,
  caption text,
  reading_minutes smallint not null check (reading_minutes > 0),
  body jsonb not null default '[]'::jsonb,
  related_slugs text[] not null default '{}',
  is_published boolean not null default false,
  published_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Ensure the JSONB field is strictly a JSON array structure.
  constraint journal_articles_body_array_check
    check (jsonb_typeof(body) = 'array')
);

-- TABLE: contact_messages
-- WHAT: Inquiries submitted through the /contact.html correspondence desk.
create table public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid references auth.users(id) on delete set null,
  full_name text not null,
  email text not null,
  enquiry_type text not null,
  subject text not null,
  message text not null,
  status public.contact_message_status not null default 'new',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- TABLE: admin_audit_logs
-- WHAT: Security audit logging of administrative activities (e.g. lot published, withdrawn).
-- WHY: Compliance requirement in financial/auction domains to monitor privileged actions.
create table public.admin_audit_logs (
  id uuid primary key default gen_random_uuid(),
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- TABLE: site_settings
-- WHAT: Key-value configuration table for global site parameters (banner notices, currencies).
create table public.site_settings (
  setting_key text primary key,
  setting_value jsonb not null,
  is_public boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =============================================================================
-- 3. Performance Indexes (B-Tree)
-- =============================================================================
-- WHY USE INDEXES:
-- Without indexes, every search or filter requires a full table scan (O(N) time).
-- B-tree indexes reduce query time to O(log N), speeding up catalogue searches,
-- bid history lookups, and category filtering.

-- Composite index for fast public catalogue browsing (status, publish date, end date).
create index auction_lots_public_listing_idx
  on public.auction_lots (status, published_at, ends_at);

-- Speeds up retrieving and ordering all gallery images for a specific lot.
create index lot_images_lot_order_idx
  on public.lot_images (lot_id, sort_order);

-- Speeds up retrieving the latest bids on an auction lot in descending order.
create index bids_lot_created_idx
  on public.bids (lot_id, created_at desc);

-- Speeds up retrieving a user's personal bid history.
create index bids_bidder_created_idx
  on public.bids (bidder_id, created_at desc);

-- Speeds up queries checking how many users have saved a specific lot.
create index saved_lots_lot_idx
  on public.saved_lots (lot_id);

-- Speeds up filtering journal stories by publication status and category.
create index journal_articles_public_category_idx
  on public.journal_articles (is_published, category, published_at desc);

-- Speeds up admin dashboard queries filtering contact inquiries by status.
create index contact_messages_status_created_idx
  on public.contact_messages (status, created_at desc);

-- Speeds up admin audit log reviews ordered by timestamp.
create index admin_audit_logs_actor_created_idx
  on public.admin_audit_logs (actor_user_id, created_at desc);

create index admin_audit_logs_entity_idx
  on public.admin_audit_logs (entity_type, entity_id, created_at desc);

